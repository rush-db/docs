const alternateVersion = alternateDocsVersion(DEFAULT_DOCS_VERSION)
const sidebarPathFor = (version: keyof typeof docsSidebarPath): string => {
  return version === '2.x' && DEFAULT_DOCS_VERSION === '3.x' ? './sidebars.v2.ts' : docsSidebarPath[version]
}
// An autogenerated directory's README is already its category's link, so it is
// not listed again as the last item inside the category.
const sidebarItemsGenerator = async ({ defaultSidebarItemsGenerator, ...args }) => {
  const items = await defaultSidebarItemsGenerator(args)
  return items.filter((item) => !(item.type === 'doc' && item.id === `${args.item.dirName}/README`))
}

const currentDocsOptions = {
  path: docsSourcePath[DEFAULT_DOCS_VERSION],
  routeBasePath: docsRouteBasePath(DEFAULT_DOCS_VERSION),
  sidebarPath: sidebarPathFor(DEFAULT_DOCS_VERSION),
  sidebarItemsGenerator
}

